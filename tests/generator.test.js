test("escapes LaTeX-sensitive user text", () => {
  assert.equal(escapeLatex("A&B_50%"), "A\\&B\\_50\\%");
});

test("maps aspect ratios to Beamer class options", () => {
  assert.equal(aspectRatioOption("16:9"), "aspectratio=169");
  assert.equal(aspectRatioOption("4:3"), "aspectratio=43");
});

test("generates a complete Beamer file set", () => {
  const files = generateFiles(DEFAULT_THEME, getRegistry());
  assert.deepEqual(Object.keys(files).sort(), [
    "README.md",
    "content/figures.tex",
    "content/overview.tex",
    "content/tables.tex",
    "main.tex",
    "theme.cls",
    "theme.json"
  ]);
  assert.match(files["main.tex"], /\\documentclass\[10pt\]\{theme\}/);
  assert.match(files["theme.cls"], /\\definecolor\{bfPrimary\}\{HTML\}\{456990\}/);
  assert.match(files["theme.cls"], /\\setbeamertemplate\{itemize item\}\{\\ding\{109\}\}/);
  assert.match(files["README.md"], /Generated by BeamerForge/);
});

test("all renderer parity stress fixtures resolve and generate stable overview landmarks", () => {
  for (const fixture of createStressFixtures()) {
    const bundle = resolveDesignBundle(fixture.theme, getRegistry());
    const files = generateResolvedFiles(bundle.design);

    assert.equal(bundle.design.capabilities.html, true, fixture.id);
    assert.equal(bundle.design.capabilities.latex, true, fixture.id);
    assert.match(files["theme.cls"], bundle.design.canvas.aspectRatio === "4:3" ? /aspectratio=43/ : /aspectratio=169/);
    assert.ok(files["content/overview.tex"].includes(bundle.design.content.sampleTitle), fixture.id);
    assert.equal(files["theme.cls"].includes("tikzpicture"), fixture.id === "duck", fixture.id);
  }
});

