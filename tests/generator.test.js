test("logo scale applies equally to TikZ line coordinates and stroke width", () => {
  const registry = getRegistry();
  const lineVector = {
    id: "line-logo",
    viewBox: [0, 0, 6, 4],
    colors: { ink: "#17202A" },
    primitives: [{
      type: "line",
      x1: 0.1,
      y1: 0.1,
      x2: 5.9,
      y2: 3.9,
      stroke: "ink",
      strokeWidth: 0.2
    }]
  };
  registry.logos["line-logo"] = {
    ...registry.logos.duck,
    id: "line-logo",
    label: "Line Logo",
    vector: lineVector,
    vectorId: "line-logo",
    previewUrl: "/assets/generated/logos/line-logo.svg"
  };
  const theme = structuredClone(DEFAULT_THEME);
  theme.decorations.cornerLogo = {
    id: "line-logo",
    position: "top-right",
    size: "small",
    scope: "content-frames"
  };

  const classFile = generateFiles(theme, registry)["theme.cls"];
  assert.match(classFile, /\\begin\{tikzpicture\}\[scale=0\.133333\]/);
  assert.match(classFile, /line width=0\.026667cm/);
  assert.doesNotMatch(classFile, /line width=0\.2cm/);
});

test("every registry-accepted boundary vector generates at both supported logo sizes", () => {
  const registry = getRegistry();
  const boundaryVector = {
    id: "boundary-polygon-logo",
    viewBox: [0, 0, 0.00012, 0.00012],
    colors: { ink: "#17202A" },
    primitives: [{
      type: "polygon",
      points: [[0, 0], [0.00012, 0], [0, 0.00012]],
      fill: "ink"
    }]
  };
  registry.logos["boundary-polygon-logo"] = {
    ...registry.logos.duck,
    id: "boundary-polygon-logo",
    label: "Boundary Polygon Logo",
    vector: boundaryVector,
    vectorId: "boundary-polygon-logo",
    previewUrl: "/assets/generated/logos/boundary-polygon-logo.svg"
  };
  assert.doesNotThrow(() => assertRegistryContract(registry));

  for (const [size, scale] of [["small", "6666.666667"], ["medium", "10000"]]) {
    const theme = structuredClone(DEFAULT_THEME);
    theme.decorations.cornerLogo = {
      id: "boundary-polygon-logo",
      position: "top-right",
      size,
      scope: "content-frames"
    };
    assert.match(
      generateFiles(theme, registry)["theme.cls"],
      new RegExp(`\\\\begin\\{tikzpicture\\}\\[scale=${scale.replace(".", "\\.")}\\]`)
    );
  }
});
